import { MessagesSquare, RotateCcw, Users } from 'lucide-react'
import type { KeyboardEvent } from 'react'
import { useLeagueFeed } from '../api/queries'
import type { FeedItem } from '../api/types'
import { describeApiError } from '../lib/home'
import { formatAbsoluteTime, formatRelativeTime } from '../lib/time'
import { Avatar } from './Avatar'
import styles from './LeagueFeed.module.css'

interface LeagueFeedProps {
  onOpenProfile: (userId: string) => void
}

function FeedCard({
  item,
  onOpenProfile,
}: {
  item: FeedItem
  onOpenProfile: (userId: string) => void
}) {
  function open() {
    onOpenProfile(item.author.id)
  }

  function onKeyDown(event: KeyboardEvent<HTMLElement>) {
    if (event.key !== 'Enter' && event.key !== ' ') return
    event.preventDefault()
    open()
  }

  return (
    <li>
      <article
        className={styles.card}
        role="button"
        tabIndex={0}
        aria-label={`查看 ${item.author.name || '选手'} 的资料`}
        data-testid="feed-item"
        onClick={open}
        onKeyDown={onKeyDown}
      >
        <div className={styles.cardHead}>
          <Avatar
            src={item.author.avatar_url}
            name={item.author.name}
            size={38}
          />
          <div className={styles.authorText}>
            <p className={styles.authorName} data-testid="feed-author">
              {item.author.name || '未命名选手'}
            </p>
            <div className={styles.authorMeta}>
              <time dateTime={item.created_at}>
                {formatRelativeTime(item.created_at)}
              </time>
              <span aria-hidden="true">·</span>
              <time dateTime={item.created_at}>
                {formatAbsoluteTime(item.created_at)}
              </time>
            </div>
          </div>
          {item.author.title ? (
            <span className={styles.tag}>{item.author.title}</span>
          ) : null}
        </div>

        <p className={styles.body}>{item.body}</p>

        {item.reactions.length > 0 || item.tags.length > 0 ? (
          <div className={styles.meta}>
            {item.reactions.map((reaction) => (
              <span
                className={styles.reaction}
                key={`reaction-${reaction.emoji}`}
              >
                <span aria-hidden="true">{reaction.emoji}</span>
                {reaction.count}
              </span>
            ))}
            {item.tags.map((tag) => (
              <span className={styles.hashtag} key={`tag-${tag.tag}`}>
                #{tag.tag}
                <span className={styles.tagCount}>{tag.count}</span>
              </span>
            ))}
          </div>
        ) : null}
      </article>
    </li>
  )
}

/**
 * Read-only group feed. Events are generated by the server from real check-ins
 * and settlements; this component never offers a composer.
 */
export function LeagueFeed({ onOpenProfile }: LeagueFeedProps) {
  const feed = useLeagueFeed()
  const items = feed.data?.items ?? []

  return (
    <section
      className={styles.panel}
      aria-labelledby="league-feed-title"
      data-testid="league-feed"
    >
      <div className={styles.head}>
        <span className={styles.headIcon} aria-hidden="true">
          <MessagesSquare size={18} />
        </span>
        <div className={styles.headText}>
          <h2 id="league-feed-title">组内动态</h2>
          <p>只展示打卡与结算产生的真实动态，不能自由发帖。</p>
        </div>
        <span className={styles.count}>{items.length} 条</span>
      </div>

      {feed.isPending ? (
        <div className={styles.state} aria-busy="true">
          <span className={styles.stateIcon} aria-hidden="true">
            <MessagesSquare size={24} />
          </span>
          <p className={styles.stateTitle}>正在读取动态</p>
        </div>
      ) : feed.isError ? (
        <div className={styles.state} role="alert">
          <span className={styles.stateIcon} aria-hidden="true">
            <MessagesSquare size={24} />
          </span>
          <p className={styles.stateTitle}>动态没有加载出来</p>
          <p className={styles.stateCopy}>{describeApiError(feed.error)}</p>
          <button
            type="button"
            className="button button--secondary"
            onClick={() => void feed.refetch()}
            disabled={feed.isFetching}
          >
            <RotateCcw size={16} aria-hidden="true" />
            {feed.isFetching ? '正在重试…' : '重试'}
          </button>
        </div>
      ) : items.length === 0 ? (
        <div className={styles.state} data-testid="feed-empty">
          <span className={styles.stateIcon} aria-hidden="true">
            <Users size={24} />
          </span>
          <p className={styles.stateTitle}>还没有组内动态</p>
          <p className={styles.stateCopy}>
            完成打卡或周结算后，真实动态会出现在这里。
          </p>
        </div>
      ) : (
        <ol className={styles.list} aria-label="组内动态">
          {items.map((item) => (
            <FeedCard
              key={item.id}
              item={item}
              onOpenProfile={onOpenProfile}
            />
          ))}
        </ol>
      )}
    </section>
  )
}
